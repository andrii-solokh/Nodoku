import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { readAdminToken } from '../scripts/admin-api.ts';

const url = process.env.TEST_URL || 'http://127.0.0.1:4173';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const state = () => page.evaluate(() => JSON.parse(window.render_game_to_text()));
const field = name => page.locator(`#config-selection-${name}`);
try {
  await page.goto(`${url}/?admin=1#admin-token=${readAdminToken(process.cwd())}`);
  await page.locator('#admin-settings').waitFor();
  await page.getByText('Selected node', { exact: true }).click();
  await page.getByRole('button', { name: 'Preview selection', exact: true }).click();
  let current = await state();
  const saved = current.config.selection;
  assert.equal(current.selected, 0);
  assert.equal(current.selectionVisuals.guides.count, 2);
  const edges = current.edges;
  await field('ringColor').fill('#cc4466');
  await field('ringSize').fill('1.5');
  await field('ringThickness').fill('2');
  await field('ringOpacity').fill('0.6');
  await field('guideColor').fill('#227799');
  await field('guideThickness').fill('2.5');
  await field('guideOpacity').fill('0.8');
  current = await state();
  assert.equal(current.selectionVisuals.ring.color, '#cc4466');
  assert.equal(current.selectionVisuals.ring.opacity, .6);
  assert.ok(Math.abs(current.selectionVisuals.ring.radius - .205 * 1.5) < 1e-8);
  assert.ok(Math.abs(current.selectionVisuals.ring.thickness - .028) < 1e-8);
  assert.equal(current.selectionVisuals.guides.color, '#227799');
  assert.equal(current.selectionVisuals.guides.opacity, .8);
  assert.ok(current.selectionVisuals.guides.radii.every(radius => Math.abs(radius - .03) < 1e-8));
  assert.deepEqual(current.edges, edges);
  await field('ringEnabled').uncheck();
  assert.equal((await state()).selectionVisuals.ring.visible, false);
  await field('ringEnabled').check();
  await field('guidesEnabled').uncheck();
  assert.equal((await state()).selectionVisuals.guides.visible, false);
  await field('guidesEnabled').check();
  await mkdir('output/web-game/selection-settings', { recursive: true });
  await page.screenshot({ path: 'output/web-game/selection-settings/desktop.png' });
  await page.locator('#admin-close').click();
  const first = (await state()).floating.selection.position;
  await page.evaluate(() => window.advanceTime(800));
  current = await state();
  assert.notDeepEqual(current.floating.selection.position, first);
  assert.deepEqual(current.floating.selection.position, current.floating.nodes.find(n => n.nodeId === 0).visual,
    'selection follows the floating node');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(200);
  await page.screenshot({ path: 'output/web-game/selection-settings/mobile.png' });
  await page.locator('#admin-open').click();
  await page.locator('#admin-reset').click();
  assert.deepEqual((await state()).config.selection, saved);
  await page.locator('#admin-close').click();
  await page.locator('#onboarding-skip').click();
  await page.locator('#start-button').click();
  await page.waitForFunction(() => JSON.parse(window.render_game_to_text()).mode === 'playing');
  const node = (await state()).nodes.find(n => n.screen?.pickable);
  await page.mouse.click(node.screen.x, node.screen.y);
  current = await state();
  assert.equal(current.selectionVisuals.nodeId, node.id);
  assert.equal(current.selectionVisuals.ring.color, saved.ringColor);
  assert.deepEqual(errors, []);
  console.log('Selection styling: live geometry/materials, visibility, unchanged edges, floating, reset and gameplay passed.');
} finally { await browser.close(); }
